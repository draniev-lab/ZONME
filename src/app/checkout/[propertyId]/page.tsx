
"use client";

import { useDoc, useFirestore, useUser } from "@/firebase";
import { Property, AppSettings, StripeCheckoutSession } from "@/lib/types";
import { notFound, useRouter, useSearchParams } from "next/navigation";
import { Loader2, CreditCard } from "lucide-react";
import { Card, CardContent, CardDescription, CardFooter, CardHeader, CardTitle } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Separator } from "@/components/ui/separator";
import { useToast } from "@/hooks/use-toast";
import { collection, addDoc, onSnapshot, doc, updateDoc } from "firebase/firestore";
import { useEffect, useState, Suspense, use } from "react";
import Image from 'next/image';

function CheckoutContent({ params }: { params: { propertyId: string } }) {
  const { data: property, loading: propertyLoading } = useDoc<Property>('properties', params.propertyId);
  const { data: settings, loading: settingsLoading } = useDoc<AppSettings>('settings', 'app');
  const { user } = useUser();
  const { firestore } = useFirestore();
  const { toast } = useToast();
  const router = useRouter();
  const searchParams = useSearchParams();

  const [isProcessing, setIsProcessing] = useState(false);

  const reservationFee = settings?.reservationFee || 0;
  const reservationFeePriceId = settings?.reservationFeePriceId;

  // Handle payment cancellation
  useEffect(() => {
    if (searchParams.get('canceled')) {
      if (firestore && property && property.status === 'Réservation') {
        const propertyRef = doc(firestore, 'properties', property.id);
        updateDoc(propertyRef, { status: 'Vente' }).then(() => {
          toast({
            variant: 'destructive',
            title: "Paiement annulé",
            description: "La réservation a été annulée et le bien est de nouveau disponible.",
          });
          router.replace(`/checkout/${property.id}`);
        });
      }
    }
  }, [searchParams, firestore, property, router, toast]);

  const formatPrice = (price: number) => {
    return new Intl.NumberFormat('fr-FR', {
      style: 'currency',
      currency: 'XOF',
      minimumFractionDigits: 0,
    }).format(price);
  };
  
  const handleCreateCheckoutSession = async () => {
    if (!user || !firestore || !property || !reservationFeePriceId) {
      toast({ variant: 'destructive', title: "Erreur", description: "Impossible de procéder au paiement. La configuration des paiements est incomplète ou les informations sont manquantes." });
      return;
    }
    setIsProcessing(true);

    const propertyRef = doc(firestore, 'properties', property.id);

    try {
      // First, set the property to 'Réservation' to prevent double booking
      await updateDoc(propertyRef, { status: 'Réservation' });

      const successUrl = `${window.location.origin}/checkout/success?propertyId=${property.id}`;
      const cancelUrl = `${window.location.origin}/checkout/${property.id}?canceled=true`;

      const checkoutSessionData: Omit<StripeCheckoutSession, 'url' | 'error'> = {
        price: reservationFeePriceId,
        success_url: successUrl,
        cancel_url: cancelUrl,
        mode: 'payment'
      };
      
      const sessionRef = await addDoc(
        collection(firestore, 'customers', user.uid, 'checkout_sessions'),
        checkoutSessionData
      );

      // Listen for the URL generated by the Stripe extension
      const unsubscribe = onSnapshot(sessionRef, (snap) => {
        const data = snap.data() as StripeCheckoutSession;
        if (data?.url) {
          unsubscribe();
          router.push(data.url);
        } else if (data?.error) {
          unsubscribe();
          console.error("Stripe Checkout Error:", data.error.message);
          toast({ variant: 'destructive', title: "Erreur de paiement", description: data.error.message });
          setIsProcessing(false);
          // Rollback status if Stripe returns an error
          updateDoc(propertyRef, { status: 'Vente' });
        }
      });

    } catch (error) {
      console.error("Failed to create checkout session:", error);
      toast({ variant: 'destructive', title: "Erreur", description: "Une erreur est survenue lors de l'initialisation du paiement." });
      // Rollback status if the initial update fails
      updateDoc(propertyRef, { status: 'Vente' });
      setIsProcessing(false);
    }
  }

  const loading = propertyLoading || settingsLoading;

  if (loading) {
    return (
      <div className="flex h-[80vh] w-full items-center justify-center">
        <Loader2 className="h-12 w-12 animate-spin text-primary" />
      </div>
    );
  }

  if (!property || (property.status === 'Réservation' && !searchParams.get('canceled'))) {
    notFound();
  }
  
  if (property.status === 'Location') {
    notFound();
  }

  return (
    <div className="container mx-auto max-w-4xl px-4 py-12">
      <div className="grid grid-cols-1 md:grid-cols-2 gap-8 items-start">
        <div>
            <h1 className="font-headline text-2xl md:text-3xl">Finaliser la réservation</h1>
            <p className="text-muted-foreground">Vous êtes sur le point de réserver le bien :</p>
            <Card className="mt-4 overflow-hidden">
                {property.imageUrls?.[0] && (
                    <div className="relative h-48 w-full">
                        <Image src={property.imageUrls[0]} alt={property.title} fill className="object-cover" />
                    </div>
                )}
                <CardHeader>
                    <CardTitle>{property.title}</CardTitle>
                    <CardDescription>{property.address}, {property.city}</CardDescription>
                </CardHeader>
                <CardContent>
                    <Separator />
                    <div className="flex justify-between items-center py-4">
                        <span className="font-medium">Frais de réservation</span>
                        <span className="font-bold text-lg">{formatPrice(reservationFee)}</span>
                    </div>
                     <Separator />
                </CardContent>
                 <CardFooter>
                    <p className="text-xs text-muted-foreground">Ces frais sont symboliques pour sécuriser le bien. Le montant sera déduit du prix final.</p>
                </CardFooter>
            </Card>
        </div>
        <div>
            <Card>
                <CardHeader>
                    <CardTitle>Paiement Sécurisé</CardTitle>
                    <CardDescription>Vous allez être redirigé vers notre partenaire de paiement pour finaliser la transaction.</CardDescription>
                </CardHeader>
                <CardContent>
                    <p className="text-sm text-muted-foreground">En cliquant sur le bouton ci-dessous, vous serez redirigé vers une page de paiement sécurisée pour compléter votre réservation. Cette étape est gérée par nos partenaires de confiance pour garantir la sécurité de vos informations.</p>
                </CardContent>
                <CardFooter>
                     <Button className="w-full flex items-center gap-2" disabled={isProcessing || !reservationFeePriceId} onClick={handleCreateCheckoutSession}>
                        <span>
                            {isProcessing ? "Initialisation..." : `Procéder au paiement de ${formatPrice(reservationFee)}`}
                        </span>
                        {(isProcessing) ? <Loader2 className="h-4 w-4 animate-spin" /> : <CreditCard className="h-4 w-4"/>}
                    </Button>
                </CardFooter>
                {!reservationFeePriceId && (
                    <CardFooter>
                        <p className="text-xs text-destructive text-center w-full">La configuration des paiements est incomplète. L'administrateur doit configurer un ID de prix.</p>
                    </CardFooter>
                )}
            </Card>
        </div>
      </div>
    </div>
  );
}


export default function CheckoutPage({ params }: { params: { propertyId: string } }) {
  return (
    <Suspense fallback={
        <div className="flex h-[80vh] w-full items-center justify-center">
            <Loader2 className="h-12 w-12 animate-spin text-primary" />
        </div>
    }>
        <CheckoutContent params={params} />
    </Suspense>
  )
}
